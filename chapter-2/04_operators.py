# Arithmetic Operators  --> + , - , * , /
a = 4
b = 5
c = a + b
print(c)

# Assignment Operator  --> = , += , -+
a = 4 - 2
print(a)

b = 5
b += 2
print(b)  # Increment the value of b by 2 then assign it in to the b

# Comparison Operator  --> == , >= , <= , != etc.

a = 4 > 5
print(a)

b = 5 != 5
print(b)

# Logical Operators --> and , or , not. 

# and = when both values are true the answer is true otherwise its false.
# or = when both values is false the answer is false otherwise it is true
# not = true become false and false become true.
 



